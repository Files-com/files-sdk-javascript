    this.delete(params)

  save = async () => {
    if (this.attributes.id) {
      await this.update(this.attributes)
      return true
    }

    const newObject = await MetadataCategory.create(this.attributes, this.options)
    adoptAttributes(this, newObject.attributes)
    return true
  }

